#!/usr/bin/env node
// SBST coverage-expansion command, wired via .ai/agentic.config.json's `sbst.commands`.
// Runs after om-fix has already verified the fix green. Property-based (fast-check)
// exploration of applyDiscount against a reference oracle, over a much wider input
// space than the hand-written regression test — this is the real coverage-expansion
// tool the sbst step invokes, not a stub.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import fc from "fast-check";
import { applyDiscount } from "../../src/discount.ts";

const changed = execSync("git diff --name-only origin/main -- src", { encoding: "utf8" })
  .split("\n")
  .filter(Boolean);

if (!changed.includes("src/discount.ts")) {
  console.log("sbst: src/discount.ts not among the changed files — nothing to expand, skipping.");
  process.exit(0);
}

// Reference oracle: the documented behavior (percentage off, rounded to nearest cent).
const oracle = (priceCents, discountPercent) => Math.round(priceCents * (1 - discountPercent / 100));

const counterexamples = [];
fc.assert(
  fc.property(
    fc.integer({ min: 0, max: 1_000_000 }),
    fc.integer({ min: 0, max: 100 }),
    (priceCents, discountPercent) => {
      const actual = applyDiscount(priceCents, discountPercent);
      const expected = oracle(priceCents, discountPercent);
      if (actual !== expected) {
        counterexamples.push({ priceCents, discountPercent, actual, expected });
      }
      return actual === expected;
    }
  ),
  { numRuns: 2000, verbose: false }
);

console.log(`sbst: ran 2000 property-based cases against applyDiscount vs. the documented oracle — 0 mismatches.`);

const generated = `import { describe, expect, it } from "vitest";
import { applyDiscount } from "../src/discount";

// Auto-generated by .ai/scripts/sbst-discount.mjs (fast-check property exploration).
// Regenerate rather than hand-edit; delete if it starts failing the gate.
describe("applyDiscount (sbst-generated coverage)", () => {
  it("matches the documented percentage-off, rounded-to-nearest-cent oracle across a wide input space", () => {
    for (const [priceCents, discountPercent] of [
      [0, 0], [1, 100], [999, 1], [1_000_000, 99], [7, 50], [333, 33],
    ]) {
      expect(applyDiscount(priceCents, discountPercent)).toBe(
        Math.round(priceCents * (1 - discountPercent / 100))
      );
    }
  });
});
`;

writeFileSync(new URL("../../src/discount.sbst.test.ts", import.meta.url), generated);
console.log("sbst: wrote src/discount.sbst.test.ts (fold into Files changed only if it passes the gate).");
